export function filterChronometerFaqItems(
  category: ChronometerFaqCategory
): ChronometerFaqItem[] {
  if (category === 'all') {
    return [...CHRONOMETER_FAQ_ITEMS];
  }
  return CHRONOMETER_FAQ_ITEMS.filter((item) => item.category === category);
}
