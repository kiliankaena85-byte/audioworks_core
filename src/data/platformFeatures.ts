/**
 * Централизованные флаги функциональных направлений платформы FMWorks.
 *
 * Направление продажи эфирного времени и медиабаинга («Горящий эфир», каталог радиостанций,
 * 4-часовой резерв слотов и пакетные квоты) переведено в спящий режим до отдельного запуска,
 * чтобы витрина работала исключительно на конверсию студийного аудиопродакшна без конфликта интересов.
 *
 * Для повторного включения раздела достаточно переключить `AIRTIME_SALES_ENABLED = true`.
 */
export const AIRTIME_SALES_ENABLED = false;

export function isAirtimeSalesEnabled(override?: boolean): boolean {
  return override ?? AIRTIME_SALES_ENABLED;
}
